import React from "react";

export default function SessionStatusBadge({ assessment }) {
  if (!assessment) return null;

  const isFallback = assessment.question_generation_mode === "fallback";

  return (
    <aside className="session-status-bar" aria-label="Assessment session status">
      <div className="session-info-group">
        <span className="session-info-label">Session ID:</span>
        <span className="session-id-value">{assessment.assessment_id}</span>
      </div>

      <div className="session-info-group">
        <span className="session-info-label">Generator:</span>
        <span
          className={`badge ${isFallback ? "badge-fallback" : "badge-ai"}`}
          title={
            isFallback
              ? "Questions selected from deterministic fallback question bank"
              : "Questions generated by configured LLM service"
          }
        >
          {isFallback ? "Deterministic Fallback Bank" : "Configured AI Generator"}
        </span>
      </div>

      <div className="session-info-group">
        <span className="session-info-label">Future STT Mode:</span>
        <span className="badge badge-stt">
          {assessment.stt_mode || "google"} (Stage 3)
        </span>
      </div>
    </aside>
  );
}
